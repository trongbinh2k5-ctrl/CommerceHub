test('API errors stay visible, filters and empty state work without fake products', async ({ page }) => {
  await page.goto('/products?search=no-such-device-qa');
  await expect(page.getByRole('heading', { name: 'Chưa có nội dung ở đây.' })).toBeVisible();
  await page.route('**/api/products?*', r => r.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'QA API unavailable' }) }));
  await page.goto('/products');
  await expect(page.getByRole('alert')).toContainText('QA API unavailable');
  await expect(page.locator('.product-card')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Thử lại' })).toBeVisible();
});
